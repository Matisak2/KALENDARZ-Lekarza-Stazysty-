export function hospitalById(id) {
  return HOSPITALS.find((h) => h.id === id) || null;
}

/** Szpital odcinka – z listy albo własne miejsce wpisane ręcznie (hospital: 'custom'). */
export function hospitalOf(seg) {
  if (!seg) return null;
  if (seg.hospital === 'custom') {
    return { id: 'custom', name: seg.customName || 'Inne miejsce', short: seg.customName || 'Inne miejsce', address: seg.customAddress || '' };
  }
  return hospitalById(seg.hospital);
}

/** Pełny opis miejsca do kalendarza: "Oddział X, Szpital Y, adres". */
export function placeText(seg) {
  const h = hospitalOf(seg);
  return [seg?.ward, h?.name, h?.address].filter(Boolean).join(', ');
}
